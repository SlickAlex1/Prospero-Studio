"""Regenerate docs/SETTINGS.md from anyps5_settings.py.

Run after changing the settings catalog:  python scripts/generate_settings_doc.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import anyps5_settings as cat  # noqa: E402


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def value(setting: cat.Setting, which: object) -> str:
    if setting.kind == "choice" and which is not None:
        return next((label for v, label in setting.choices if v == which), str(which))
    if setting.key == "--to-intel" and which is setting.recommended:
        return "ON for Intel CPUs, OFF for AMD"
    return cat.format_value(which)


def table(settings: list[cat.Setting], key_title: str) -> list[str]:
    lines = []
    groups: dict[str, list[cat.Setting]] = {}
    for s in settings:
        groups.setdefault(s.group, []).append(s)
    for group, members in groups.items():
        lines += [f"### {group}", "", f"| {key_title} | Setting | Default | Recommended | What it does |",
                  "|---|---|---|---|---|"]
        for s in members:
            key = f"`{s.key}`" if s.key.startswith(("-", "ANYPS5", "APS5", "VK_")) or s.group in (
                "Controller", "Mouse as right stick") else "tool option"
            # The --to-intel note names the CPU of the machine running this script; drop that part.
            note = re.sub(r"\s*\(detected: [^)]*\)", "", s.note)
            text = s.description + (f" **{note}**" if note else "")
            if s.requires:
                text += f" Requires `{s.requires}`."
            if s.deprecated:
                text = "**Deprecated upstream.** " + text
            lines.append(f"| {key} | {cell(s.label)} | {cell(value(s, s.default))} | "
                         f"{cell(value(s, s.recommended))} | {cell(text)} |")
        lines.append("")
    return lines


def main() -> int:
    out = [
        "# Settings reference",
        "",
        "<!-- Generated by scripts/generate_settings_doc.py from anyps5_settings.py. Do not edit by hand. -->",
        "",
        "Every setting the GUI offers, with AnyPS5's own default and the value this tool recommends. "
        "Sources: AnyPS5 [`docs/user/USAGE.md`](https://github.com/boykopovar/AnyPS5/blob/main/docs/user/USAGE.md) "
        "and [`docs/user/INPUT_MAPPING.md`](https://github.com/boykopovar/AnyPS5/blob/main/docs/user/INPUT_MAPPING.md).",
        "",
        "Settings that the installed AnyPS5 release does not contain are greyed out in the GUI.",
        "",
        "## Build options",
        "",
        "Used when the game is converted. Changing them requires a new build. On the command line pass the flag "
        "to `anyps5_folder.py` (tool options: `--no-audit`, `--no-backup-output`, `--no-update`).",
        "",
        *table(cat.BUILD_SETTINGS, "Flag"),
        "## Runtime settings",
        "",
        "Environment variables the AnyPS5 libraries read when the game starts. The GUI applies them on **Play** "
        "and every build writes them to `play.bat`. On the command line: `--env NAME=VALUE`.",
        "",
        *table(cat.RUNTIME_SETTINGS, "Variable"),
        "## Controller and mouse",
        "",
        "Written to `anyps5-input.ini` beside `eboot.exe`. Controllers (Xbox / PlayStation layouts via SDL) "
        "work without any configuration.",
        "",
        *table(cat.INPUT_SETTINGS, "Key"),
        "Bindings: one per line, `Action = KEY:<SDL key name>`, `MOUSE:Left|Middle|Right|X1|X2` or "
        "`WHEEL:Up|Down`. The first line for an action replaces its built-in binding; further lines add "
        "alternates. Actions: " + ", ".join(f"`{a}`" for a in cat.INPUT_ACTIONS) + ".",
        "",
        "## Developer switches",
        "",
        "The **Developer switches** tab lists every other `ANYPS5_*` / `APS5_*` variable found in the AnyPS5 "
        "source (several hundred). They are undocumented internals for AnyPS5 developers, change often, and "
        "can stop a game when set wrongly. Leave them empty unless an AnyPS5 developer asks you to set one.",
        "",
    ]
    target = ROOT / "docs" / "SETTINGS.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
